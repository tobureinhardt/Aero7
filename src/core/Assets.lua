	local semanticKey = (type(key) == "string" and key ~= "") and key or "WindowDefault"
	local resolved = Assets.GetIcon(semanticKey)

	-- Always builds a vector fallback beneath image for 100% instant rendering
	-- (prevents blank/missing frames during load or decal ID resolution)
	local fallbackHolder = Assets.RenderProceduralFallback(imageLabel, semanticKey)

	if resolved ~= "" and (imageLabel:IsA("ImageLabel") or imageLabel:IsA("ImageButton")) then
		imageLabel.Image = resolved
		imageLabel.ImageTransparency = 0

		local function syncLoadedState()
			local ok, loaded = pcall(function()
				return imageLabel.IsLoaded
			end)
			if ok and loaded == true then
				if fallbackHolder and fallbackHolder.Parent then
					fallbackHolder.Visible = false
				end
				return true
			end
			if fallbackHolder and fallbackHolder.Parent then
				fallbackHolder.Visible = true
			end
			return false
		end

		if not syncLoadedState() then
			pcall(function()
				if imageLabel.GetPropertyChangedSignal then
					imageLabel:GetPropertyChangedSignal("IsLoaded"):Connect(function()
						syncLoadedState()
					end)
				end
			end)
		end
	else
		if imageLabel:IsA("ImageLabel") or imageLabel:IsA("ImageButton") then
			imageLabel.Image = ""
			imageLabel.ImageTransparency = 1
		end
	end
end

-- Binds icon to an ImageLabel or Frame with persistent fallback rendering
function Assets.BindIcon(imageLabel, iconNameOrAssetId)
	if not imageLabel then
		return
	end
	local key = (iconNameOrAssetId ~= nil and iconNameOrAssetId ~= "") and iconNameOrAssetId or "WindowDefault"
	applyBoundIconToInstance(imageLabel, key)

	local found = false
	for _, entry in ipairs(activeBindings) do
		if entry.Instance == imageLabel then
			entry.Key = key
			found = true
			break
		end
	end
	if not found then
		table.insert(activeBindings, {
			Instance = imageLabel,
			Key = key,
		})
	end
end

-- Updates icon pack registry at runtime and synchronizes all active bindings
function Assets.SetIcons(customIconTable)
	if type(customIconTable) ~= "table" then
		return
	end
	for k, v in pairs(customIconTable) do
		if type(v) == "string" and v ~= "" then
			Assets.Icons[k] = Assets.GetIcon(v) ~= "" and Assets.GetIcon(v) or v
		elseif type(v) == "number" then
			Assets.Icons[k] = "rbxassetid://" .. tostring(v)
		end
	end

	-- Updates all existing bound ImageLabels
	for i = #activeBindings, 1, -1 do
		local entry = activeBindings[i]
		local inst = entry.Instance
		if inst and inst.Parent then
			applyBoundIconToInstance(inst, entry.Key)
		else
			table.remove(activeBindings, i)
		end
	end
end

return Assets
