local function clearProceduralChildren(parent)
	for _, child in ipairs(parent:GetChildren()) do
		if child.Name == "_Win7ProceduralIcon" then
			child:Destroy()
		end
	end
end

local function makeFrame(parent, name, pos, size, bg, trans, radius, rot)
	local f = Instance.new("Frame")
	f.Name = name or "_Win7ProceduralIcon"
	f.Position = pos
	f.Size = size
	f.BackgroundColor3 = bg or Color3.fromRGB(255, 255, 255)
	f.BackgroundTransparency = trans or 0
	f.BorderSizePixel = 0
	f.ZIndex = (parent and parent.ZIndex or 6) + 1
	if rot and rot ~= 0 then
		f.Rotation = rot
	end
	if radius and radius > 0 then
		local c = Instance.new("UICorner")
		c.CornerRadius = UDim.new(0, radius)
		c.Parent = f
	end
	f.Parent = parent
	return f
end

-- Rounded thin rotated bars for anti-aliased vector icon diagonal strokes
local function makeBar(parent, name, cx, cy, len, thick, rot, color, trans, z)
	local bar = makeFrame(
		parent,
		name,
		UDim2.new(0.5, cx, 0.5, cy),
		UDim2.new(0, len, 0, thick),
		color,
		trans or 0,
		math.max(1, math.floor(thick / 2)),
		rot
	)
	bar.AnchorPoint = Vector2.new(0.5, 0.5)
	if z then
		bar.ZIndex = z
	end
	return bar
end

local function applyGradient(frame, c0, c1, rot)
	local g = Instance.new("UIGradient")
	g.Color = ColorSequence.new({
		ColorSequenceKeypoint.new(0, c0),
		ColorSequenceKeypoint.new(1, c1),
	})
	g.Rotation = rot or 90
	g.Parent = frame
	return g
end

