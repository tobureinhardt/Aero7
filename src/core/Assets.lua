-- Resolves asset ID by name, DLL path, or raw rbxassetid / numeric string
function Assets.GetIcon(iconNameOrAssetId)
	if type(iconNameOrAssetId) == "number" then
		return "rbxassetid://" .. tostring(iconNameOrAssetId)
	end
	if type(iconNameOrAssetId) ~= "string" or iconNameOrAssetId == "" then
		return ""
	end
	if
		iconNameOrAssetId:find("^rbxassetid://")
		or iconNameOrAssetId:find("^rbxthumb://")
		or iconNameOrAssetId:find("^http")
		or iconNameOrAssetId:find("^rbxasset://")
	then
		return iconNameOrAssetId
	end
	if iconNameOrAssetId:match("^%d+$") then
		return "rbxassetid://" .. iconNameOrAssetId
	end
	return Assets.Icons[iconNameOrAssetId] or ""
end

local function applyBoundIconToInstance(imageLabel, key)
	if not imageLabel then
